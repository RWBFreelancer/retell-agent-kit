#!/usr/bin/env python3
"""Set the silent-caller fields on the AGENT. Dry run by default. Never publishes.

For the common ask "one reminder, then hang up on a truly silent caller,
never on faint speech or 'hold on'":

WHAT IT SETS

    reminder_max_count         -> 1       one extra attempt, not two
    end_call_after_silence_ms  -> TARGET  see --silence-ms

`reminder_trigger_ms` stays at the agent's current value. Nothing else on
the agent is touched.

HOW RETELL TIMES THIS (see docs.retellai.com/api-references/create-agent)

    reminder_trigger_ms: triggers a reminder to the agent to speak if the
    user has been silent for the specified duration after some agent speech.
    reminder_max_count: how many times the agent reminds an unresponsive
    user.
    end_call_after_silence_ms: if the user stays silent after agent speech
    for this long, end the call. Retell's minimum is 10,000 ms.

Both timers run from the end of agent speech, so a reminder restarts the
hang-up timer.

WHY AN AGENT SETTING AND NOT THE FLOW

Silence-driven reminders are generated by Retell, not by a node, so no flow
transform can see or count them. `agenttiming.py` sets only responsiveness
and interruption sensitivity; it does not touch these fields.

WHAT IT DOES TO "HOLD ON"

The same timers run on every silence, including a caller who says "hold
on". With one reminder, that caller gets reminder_trigger_ms plus about 4 s
of reminder plus end_call_after_silence_ms of quiet before the call ends.
Choose --silence-ms with that in mind, and check real calls before and
after the change. See `check-agent-data`.

GUARDS

  - Dry run by default. `--push` is required to PATCH.
  - Refuses unless the latest agent version is a DRAFT.
  - Prints old value, new value, and direction for each field.
  - Snapshots the agent to <client>/agents/<agent>/exports/ before writing.
  - Verifies from a fresh GET after writing.
  - Never publishes.

USAGE

    python tools/agentsilence.py --client acme --agent intake --silence-ms 30000
    python tools/agentsilence.py --client acme --agent intake --silence-ms 30000 --push

REVERSAL

    The pre-change snapshot under <client>/agents/<agent>/exports/ holds the
    old values. Set them back with the same flags.
"""
import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "kit"))

try:
    sys.stdout.reconfigure(encoding="utf-8")
except (AttributeError, ValueError):
    pass

from retellkit import RetellClient, RetellError, agent_config, load_env


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--client", required=True, help="client folder name")
    ap.add_argument("--agent", required=True, help="agent slug under <client>/agents/")
    ap.add_argument("--silence-ms", type=int, required=True,
                    help="end_call_after_silence_ms. Retell minimum 10000.")
    ap.add_argument("--reminder-count", type=int, default=1,
                    help="reminder_max_count. Default 1: one extra attempt.")
    ap.add_argument("--push", action="store_true",
                    help="actually PATCH the draft agent. Never publishes.")
    args = ap.parse_args(argv)
    if args.silence_ms < 10000:
        raise SystemExit("--silence-ms below Retell's minimum of 10000")

    load_env()
    cfg = agent_config(args.client, args.agent)
    client = RetellClient()
    agent_id = cfg["agent_id"]
    target = {"reminder_max_count": args.reminder_count,
              "end_call_after_silence_ms": args.silence_ms}

    print("=" * 74)
    print("agentsilence  |  agent %s  |  %s" % (args.agent.upper(), agent_id))
    print("=" * 74)

    versions = client.list_agent_versions(agent_id)
    if not versions:
        raise RetellError("no agent versions returned")
    latest = versions[0]
    if latest.get("is_published"):
        raise SystemExit(
            "agent v%s is PUBLISHED and may be carrying live calls. Create a "
            "draft first, then re-run." % latest.get("version"))
    print("  agent v%s is a DRAFT. OK." % latest.get("version"))

    agent = client.get_agent(agent_id, latest.get("version"))
    trigger = agent.get("reminder_trigger_ms")

    print("\n  field                        now       ->  new")
    print("  " + "-" * 56)
    changes = {}
    for k, want in target.items():
        have = agent.get(k)
        word = "same" if have == want else ("up" if want > have else "down")
        print("  %-28s %-9s ->  %-8s %s" % (k, have, want, word))
        if have != want:
            changes[k] = want

    print("\n  NOT CHANGED, but it sets the timing")
    for k in ("reminder_trigger_ms", "responsiveness", "interruption_sensitivity",
              "max_call_duration_ms"):
        print("    %-28s %r" % (k, agent.get(k)))

    def total(count, silence):
        return (trigger or 0) * count / 1000 + 4 * count + silence / 1000
    print("\n  QUIET BEFORE HANG-UP, after the agent's last line (reminder ~4 s)")
    print("    now : %.0f s" % total(agent.get("reminder_max_count") or 0,
                                     agent.get("end_call_after_silence_ms") or 0))
    print("    new : %.0f s" % total(args.reminder_count, args.silence_ms))

    if not changes:
        print("\n  Nothing to change.")
        return 0

    snap = Path(cfg["exports"]) / ("v%s-agent-pre-silence.json" % latest.get("version"))
    snap.parent.mkdir(parents=True, exist_ok=True)
    snap.write_text(json.dumps(agent, indent=2, ensure_ascii=False), encoding="utf-8")
    print("\n  snapshot: %s" % snap)

    if not args.push:
        print("\nDRY RUN. Nothing was written to Retell.")
        return 0

    client.update_agent(agent_id, changes, version=latest.get("version"))
    back = client.get_agent(agent_id, latest.get("version"))
    ok = True
    print("\n  VERIFY, from a fresh GET")
    for k, want in target.items():
        got = back.get(k)
        ok = ok and got == want
        print("    %-28s %-8s %s" % (k, got, "MATCHES" if got == want else "DOES NOT MATCH"))
    for k in ("reminder_trigger_ms", "responsiveness", "interruption_sensitivity"):
        same = back.get(k) == agent.get(k)
        ok = ok and same
        print("    %-28s %-8s %s" % (k, back.get(k), "unchanged" if same else "MOVED"))
    post = Path(cfg["exports"]) / ("v%s-agent-post-silence.json" % back.get("version"))
    post.write_text(json.dumps(back, indent=2, ensure_ascii=False), encoding="utf-8")
    print("    snapshot: %s" % post)
    print("\n  NOT PUBLISHED. Publish by hand, then run delivery-check.")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
