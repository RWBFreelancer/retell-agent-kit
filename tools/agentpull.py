#!/usr/bin/env python3
"""Snapshot the Retell AGENT object into the repo. Read-only.

Why this exists. `flowpull.py` snapshots the ConversationFlow and nothing else.
Every agent-level setting - voice, latency, denoising, DTMF, boosted keywords,
guardrails, webhook, and all of post_call_analysis_data - lives on the Agent
object. Nothing else in this kit mirrors it, so notes about an agent can
drift away from the live settings unnoticed unless this is run.

This tool writes two files per agent:

    agents/<agent>/agent-settings.json   the exact object, for diffing
    agents/<agent>/AGENT-SETTINGS.md     the same thing a human can read

It never writes to Retell. It has no --push. Compare with `git diff` after a
run: any change there is drift between the repo and the live agent.

Usage:
    python tools/agentpull.py --client acme-dental --agent intake
    python tools/agentpull.py --client acme-dental --agent intake --version 22
    python tools/agentpull.py --help
"""
import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "kit"))

try:
    sys.stdout.reconfigure(encoding="utf-8")
except (AttributeError, ValueError):
    pass

from retellkit import RetellClient, RetellError, agent_config, load_env  # noqa: E402

# Keys that change on every read and would make every diff noisy.
VOLATILE = ("last_modification_timestamp",)

# How the readable report is grouped. Anything not named here still lands in
# the JSON and is listed under "Other" in the report, so a new Retell setting
# can never be silently dropped.
GROUPS = [
    ("Identity", ["agent_id", "agent_name", "version", "base_version",
                  "is_published", "channel", "language", "timezone",
                  "assigned_tags"]),
    ("Response engine", ["response_engine"]),
    ("Voice", ["voice_id", "fallback_voice_ids", "voice_model",
               "voice_temperature", "voice_speed", "enable_dynamic_voice_speed",
               "volume", "ambient_sound", "ambient_sound_volume"]),
    ("Turn taking and latency", ["responsiveness", "enable_dynamic_responsiveness",
                                 "interruption_sensitivity", "begin_message_delay_ms",
                                 "reminder_trigger_ms", "reminder_max_count",
                                 "end_call_after_silence_ms", "max_call_duration_ms"]),
    ("Audio and speech", ["stt_mode", "denoising_mode", "boosted_keywords",
                          "vocab_specialization", "normalize_for_speech"]),
    ("Keypad (DTMF)", ["allow_user_dtmf", "allow_dtmf_interruption",
                       "user_dtmf_options"]),
    ("Safety and privacy", ["guardrail_config", "pii_config",
                            "data_storage_setting", "opt_in_signed_url"]),
    ("Handbook", ["handbook_config"]),
    ("Webhook and analysis", ["webhook_url", "webhook_events",
                              "post_call_analysis_model"]),
]

# Settings that must ALWAYS appear in the mirror, even when Retell omits them
# from the response because they are null.
#
# Why this exists: `webhook_url` can be unset on a published version and
# Retell omits null fields, so the row simply disappears from
# AGENT-SETTINGS.md and the key vanishes from agent-settings.json. A `git
# diff` then shows a DELETED LINE, which reads as tidying, not as an outage.
#
# A missing delivery setting must look like a fault, not like an absence.
REQUIRED = ["webhook_url", "webhook_events"]


def fetch(client_name, agent_slug, version=None, env=None):
    """GET the agent object. Returns (cfg, agent_dict)."""
    env = env if env is not None else load_env()
    cfg = agent_config(client_name, agent_slug)
    client = RetellClient(env)
    agent = client.get_agent(cfg["agent_id"], version)
    if not agent.get("agent_id"):
        raise RetellError("response had no agent_id; refusing to write a file")
    return cfg, agent


def fmt(value):
    """One cell of the readable table."""
    if isinstance(value, (dict, list)):
        return "`" + json.dumps(value, ensure_ascii=False) + "`"
    if value is None:
        return "_not set_"
    if isinstance(value, bool):
        return "true" if value else "false"
    return f"`{value}`"


def report(label, agent):
    """Build the human-readable mirror."""
    seen = set()
    out = [f"# {label} - Retell agent settings", "",
           "Generated by `tools/agentpull.py`. Do not edit by hand.",
           "Re-run the tool and read `git diff` instead; a diff here is drift",
           "between this repository and the live Retell agent.", ""]

    fields = agent.get("post_call_analysis_data") or []

    for title, keys in GROUPS:
        rows = [(k, agent.get(k)) for k in keys
                if k in agent or k in REQUIRED]
        seen.update(k for k, _ in rows)
        if not rows:
            continue
        out += [f"## {title}", "", "| Setting | Value |", "|---|---|"]
        out += [f"| `{k}` | {fmt(v)} |" for k, v in rows]
        out.append("")

    seen.add("post_call_analysis_data")
    other = sorted(k for k in agent if k not in seen and k not in VOLATILE)
    if other:
        out += ["## Other", "",
                "Not yet grouped. Add it to `GROUPS` in `tools/agentpull.py`.",
                "", "| Setting | Value |", "|---|---|"]
        out += [f"| `{k}` | {fmt(agent[k])} |" for k in other]
        out.append("")

    out += [f"## Post-call analysis fields ({len(fields)})", "",
            "| # | Type | Name | Description |", "|---|---|---|---|"]
    for i, f in enumerate(fields, 1):
        desc = (f.get("description") or "").replace("|", "&#124;").replace("\n", " ")
        if len(desc) > 160:
            desc = desc[:157] + "..."
        out.append(f"| {i} | {f.get('type')} | `{f.get('name')}` | {desc} |")
    out.append("")
    return "\n".join(out)


def pull(client_name, agent_slug, version=None, env=None):
    """Fetch and write both files. Returns (json_path, md_path)."""
    cfg, agent = fetch(client_name, agent_slug, version, env)
    stable = {k: v for k, v in agent.items() if k not in VOLATILE}
    # Record a required setting as an explicit null rather than letting it
    # vanish, so drift shows up as a CHANGED value in `git diff`.
    for k in REQUIRED:
        stable.setdefault(k, None)

    root = Path(cfg["exports"]).parent
    json_path = root / "agent-settings.json"
    md_path = root / "AGENT-SETTINGS.md"

    json_path.write_text(
        json.dumps(stable, indent=2, ensure_ascii=False, sort_keys=True) + "\n",
        encoding="utf-8")
    md_path.write_text(report(f"{client_name}/{agent_slug}", stable), encoding="utf-8")
    return json_path, md_path, stable


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--client", required=True, help="client folder name")
    ap.add_argument("--agent", required=True, help="agent slug under <client>/agents/")
    ap.add_argument("--version", type=int, default=None,
                    help="agent version; latest by default")
    a = ap.parse_args(argv)

    try:
        json_path, md_path, agent = pull(a.client, a.agent, a.version)
    except RetellError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    print(f"agent        : {agent.get('agent_name')}")
    print(f"agent_id     : {agent.get('agent_id')}")
    print(f"version      : {agent.get('version')} "
          f"({'published' if agent.get('is_published') else 'draft'})")
    print(f"analysis     : {len(agent.get('post_call_analysis_data') or [])} fields")
    print(f"saved        : {json_path}")
    print(f"saved        : {md_path}")
    print("\nNothing was written to Retell.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
